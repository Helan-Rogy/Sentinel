"""Executive & Post-Incident Forensic Report Generator.

Generates comprehensive, C-suite ready incident reports in both Markdown and HTML formats,
incorporating agent reasoning, MTTA metrics, dynamic sandbox traces, and response recommendations.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from contracts import Incident, RiskLevel


def generate_markdown_report(incident: Incident) -> str:
    """Generate a formal executive post-incident report in GitHub-flavored Markdown."""
    created_str = incident.created.strftime("%Y-%m-%d %H:%M:%S UTC")
    updated_str = incident.updated.strftime("%Y-%m-%d %H:%M:%S UTC")
    level_str = incident.assessment.level.value.upper() if incident.assessment else "UNKNOWN"
    score_pct = round(incident.assessment.score * 100) if incident.assessment else 0

    # Extract LLM / reasoning step if available
    reasoning_step = next((s.text for s in incident.steps if s.kind == "reasoning"), None)
    summary_text = reasoning_step or (incident.assessment.summary if incident.assessment else incident.title)

    # Sandbox section
    sandbox_md = ""
    if incident.sandbox:
        sb = incident.sandbox
        conns_rows = "\n".join(
            f"| `{c.get('ip')}` | `{c.get('port')}` | `{c.get('proto')}` | {c.get('threat', 'Unclassified')} |"
            for c in sb.network_connections
        ) or "| None | - | - | -"
        sandbox_md = f"""
## 4. Isolated Kali Sandbox Dynamic Telemetry
* **Analysis Backend**: `{sb.backend}` ({sb.vm_name})
* **VM Containment State**: `{sb.vm_state.upper()}`
* **Execution Duration**: `{sb.duration_seconds}s`
* **Files Touched**: `{sb.files_touched}` | **Encrypted-like Files**: `{sb.files_encrypted_like}`
* **Observed Extensions**: `{", ".join(sb.extensions_changed) or "None"}`

### Network C2 Beacons & Communications
| Destination IP | Port | Protocol | Threat Classification |
|---|---|---|---|
{conns_rows}

### Dropped Artifacts
{chr(10).join(f"- `{f}`" for f in sb.dropped_files) if sb.dropped_files else "- No dropped files recorded"}
"""

    report_md = f"""# AEGIS SENTINEL // EXECUTIVE FORENSIC INCIDENT REPORT
**CONFIDENTIAL // SOC TIER-3 INVESTIGATION**

---

### Incident Summary
* **Incident ID**: `{incident.id}`
* **Detection Timestamp**: {created_str}
* **Last Updated**: {updated_str}
* **Severity Level**: **{level_str} ({score_pct}% Threat Score)**
* **Current Status**: `{incident.status.value.upper()}`
* **Attributed Origin**: `{incident.process_name or 'Unattributed'}` (PID: `{incident.pid or 'N/A'}`)

---

## 1. Executive Summary & Impact Analysis
> {summary_text}

| Metric | Recorded Value | Evaluation |
|---|---|---|
| **Threat Score** | `{incident.assessment.score if incident.assessment else 0.0:.3f}` | Critical Intervention Level |
| **Monitored Canary Hits** | `{len(incident.honey_hits)}` files | Early Tripwire Triggered |
| **Files Impacted** | `{incident.affected_files}` files | Contained before mass propagation |
| **Origin Process** | `{incident.process_name}` | PID: `{incident.pid}` |
| **Allowlist Check** | `{next((u for u in (incident.assessment.uncertainty if incident.assessment else []) if 'allowlist' in u.lower()), 'Not Verified')}` | Policy Verified |

---

## 2. Technical Evidence & Telemetry Signals

### Evaluated Threat Signals
| Signal Name | Value | Weight | Telemetry Details |
|---|---|---|---|
{chr(10).join(f"| `{s.name}` | `{s.value}` | `{round(s.weight * 100)}%` | {s.detail} |" for s in (incident.assessment.signals if incident.assessment else []))}

### Tripwire Canary Decoys Intercepted
{chr(10).join(f"- `{h.path}` ({h.op.value}) at `{h.ts.strftime('%H:%M:%S UTC')}`" for h in incident.honey_hits) if incident.honey_hits else "- No canary files were touched."}

---

## 3. Autonomous Response Actions
{chr(10).join(f"- **{a.kind.value.upper()}** (Target: `{a.target or a.pid}`): Status = `{a.status.value.upper()}` | *{a.rationale}*" for a in incident.actions)}
{sandbox_md}
---

## 5. Strategic Recommendations for SOC Leadership
1. **Host Isolation**: Ensure endpoint `{incident.endpoint_id}` is partitioned from lateral subnet routing.
2. **Credential Rotation**: Rotate local administrator and service account credentials associated with PID `{incident.pid}`.
3. **Backup Verification**: Validate immutable shadow copies and offline backup integrity for affected drive shares.
4. **YARA Deployment**: Deploy the auto-generated YARA detection rule across enterprise EDR sensors.

---
*Generated by Aegis Sentinel Autonomous Defense Agent v0.1.0*
"""
    return report_md.strip()
